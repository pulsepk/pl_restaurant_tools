    print(('\n%s\n[Restaurant Tools] Prop Attachment Tool — generated by %s for "%s" on bone %d:\n    %s\n%s\n')
        :format(('='):rep(60), GetPlayerName(src), model, boneId, code, ('='):rep(60)))
end)
