RegisterNetEvent(ResourceEvent('propattach:output'))
AddEventHandler(ResourceEvent('propattach:output'), function(model, boneId, code)
    local src = source
    if not IsPlayerAceAllowed(tostring(src), Config.AcePermission) then return end
    if type(code) ~= 'string' or #code > 8000 then return end
    if type(model) ~= 'string' or #model > 200 then model = '?' end
