-- ── Restaurant Tools (server) ────────────────────────────────────────────────
-- Validates the ace permission and prints generated code to server console.
-- hasBuilderAccess is also exposed as a plain export so other resources
-- (e.g. pl_burgershot's own dev-only test commands) can gate on the same
-- permission without duplicating the ace-check.

lib.callback.register(ResourceEvent('hasBuilderAccess'), function(source)
    return IsPlayerAceAllowed(tostring(source), Config.AcePermission)
end)

exports('hasBuilderAccess', function(src)
    return IsPlayerAceAllowed(tostring(src), Config.AcePermission)
end)

RegisterNetEvent(ResourceEvent('locationbuilder:output'))
AddEventHandler(ResourceEvent('locationbuilder:output'), function(code)
    local src = source
    if not IsPlayerAceAllowed(tostring(src), Config.AcePermission) then return end
    if type(code) ~= 'string' or #code > 8000 then return end
    print(('\n%s\n[Restaurant Tools] Location Builder — generated by %s — paste into Location.Management in location.lua:\n%s\n%s\n')
        :format(('='):rep(60), GetPlayerName(src), code, ('='):rep(60)))
end)

